import tempfile
import unittest
from pathlib import Path

from app.agent import LLMGeneration, RiceDiseaseAgent, SessionStore
from app.agent.rice_agent import MODEL_CLASS_ENGLISH_NAMES, MODEL_CLASS_IDS


class FakeLocalLLM:
    def __init__(self):
        self.calls = []

    def status(self):
        return {
            "ready": True,
            "provider": "fake_local",
            "model": "fake-qwen",
            "external_api": False,
        }

    def generate(self, *, system_prompt, user_prompt, history=None):
        self.calls.append(
            {
                "system_prompt": system_prompt,
                "user_prompt": user_prompt,
                "history": history or [],
            }
        )
        text = "A response generated by the language model from RAG evidence."
        if '"missing_context":"age_days"' in user_prompt:
            text += " About how many days ago was the rice seeded or transplanted?"
        if '"assessment":"uncertain"' in user_prompt:
            text += " The result is uncertain; narrow brown leaf spot is another possibility."
        if "ngập" in user_prompt.lower():
            text += " Prioritize drainage and do not add more water."
        return LLMGeneration(
            text=text,
            model="fake-qwen",
            latency_seconds=0.01,
            prompt_tokens=100,
            output_tokens=20,
            tokens_per_second=100.0,
        )


class MetaFollowUpLLM(FakeLocalLLM):
    def generate(self, *, system_prompt, user_prompt, history=None):
        return LLMGeneration(
            text=(
                "The model classified the image as bacterial leaf blight. "
                "We are missing the crop age, so ask the grower how many days ago "
                "the rice was seeded or transplanted."
            ),
            model="fake-qwen",
        )


class RepeatingDiagnosisLLM(FakeLocalLLM):
    def generate(self, *, system_prompt, user_prompt, history=None):
        self.calls.append(
            {
                "system_prompt": system_prompt,
                "user_prompt": user_prompt,
                "history": history or [],
            }
        )
        return LLMGeneration(
            text=(
                "The model classified the image as Leaf Blast. "
                "During the Rice blast (leaf blast) stage, remove infected plant "
                "material and avoid spreading it."
            ),
            model="fake-qwen",
        )


class UnrequestedQuestionLLM(FakeLocalLLM):
    def generate(self, *, system_prompt, user_prompt, history=None):
        return LLMGeneration(
            text="Maintain good airflow around the crop. What fertilizer have you applied?",
            model="fake-qwen",
        )


class RiceDiseaseAgentTests(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        store = SessionStore(Path(self.temp_dir.name) / "sessions.sqlite3")
        self.llm = FakeLocalLLM()
        self.agent = RiceDiseaseAgent(session_store=store, llm=self.llm)

    def tearDown(self):
        self.temp_dir.cleanup()

    def test_knowledge_matches_every_model_class(self):
        self.assertEqual(set(MODEL_CLASS_IDS), set(self.agent.classes))
        self.assertEqual(set(MODEL_CLASS_IDS), set(MODEL_CLASS_ENGLISH_NAMES))
        self.assertEqual(9, len(self.agent.classes))

    def test_start_asks_context_not_visible_lesion_description(self):
        result = self.agent.start_diagnosis(
            "Rice__LeafBlast",
            confidence=0.82,
            top_predictions=[
                {"class_id": "Rice__LeafBlast", "confidence_score": 0.82},
                {"class_id": "Rice__BrownSpot", "confidence_score": 0.10},
            ],
        )
        message = result["message"].lower()
        self.assertIn("how many days", message)
        self.assertNotIn("shape of the lesions", message)
        self.assertNotIn("color of the lesions", message)
        self.assertEqual("age_days", result["pending_field"])
        self.assertEqual("local_llm", result["generation"]["mode"])

    def test_start_uses_validated_profile_context_before_asking_questions(self):
        result = self.agent.start_diagnosis(
            "Rice__LeafBlast",
            confidence=0.82,
            initial_context={
                "rice_variety": "IR64",
                "age_days": 35,
                "growth_stage": "tillering",
                "recent_weather": "rainy_humid",
                "water_condition": "adequate",
                "nitrogen_use": "balanced",
            },
        )

        self.assertEqual(35, result["context"]["age_days"])
        self.assertEqual("đẻ nhánh", result["context"]["growth_stage"])
        self.assertEqual("IR64", result["context"]["rice_variety"])
        self.assertIsNone(result["pending_field"])
        self.assertIsNone(result["next_question"])
        self.assertNotIn("how many days", result["message"])
        self.assertIn('"rice_variety":"IR64"', self.llm.calls[-1]["user_prompt"])
        self.assertIn('"growth_stage":"tillering"', self.llm.calls[-1]["user_prompt"])
        self.assertNotIn('"growth_stage":"đẻ nhánh"', self.llm.calls[-1]["user_prompt"])

    def test_start_asks_only_for_profile_context_that_is_still_missing(self):
        result = self.agent.start_diagnosis(
            "Rice__LeafBlast",
            confidence=0.82,
            initial_context={
                "age_days": 35,
                "growth_stage": "tillering",
                "recent_weather": "normal",
            },
        )

        self.assertEqual("water_condition", result["pending_field"])
        self.assertNotIn("how many days", result["message"])
        self.assertIn("root zone", result["message"])

    def test_start_rejects_unknown_or_invalid_profile_context(self):
        for context in (
            {"unknown_field": "value"},
            {"age_days": True},
            {"age_days": 300},
            {"water_condition": "wet"},
        ):
            with self.subTest(context=context):
                with self.assertRaises(ValueError):
                    self.agent.start_diagnosis(
                        "Rice__LeafBlast", initial_context=context
                    )

    def test_meta_follow_up_is_replaced_with_a_direct_question(self):
        self.agent.llm = MetaFollowUpLLM()
        result = self.agent.start_diagnosis(
            "Rice__BacterialLeafBlight", confidence=0.82
        )
        message = result["message"]
        self.assertNotIn("ask the grower", message.lower())
        self.assertTrue(
            message.endswith("About how many days ago was the rice seeded or transplanted?")
        )

    def test_rag_prompt_contains_prediction_context_and_sources(self):
        self.agent.start_diagnosis("Rice__LeafBlast", confidence=0.82)
        prompt = self.llm.calls[-1]["user_prompt"]
        self.assertIn("RAG_CONTEXT", prompt)
        self.assertIn("Rice blast (leaf blast)", prompt)
        self.assertNotIn("Rice__LeafBlast", prompt)
        self.assertIn("IRRI Rice Knowledge Bank - Blast", prompt)
        self.assertIn("Classification confidence", prompt)
        self.assertIn(
            "Always answer in clear, natural English",
            self.llm.calls[-1]["system_prompt"],
        )

    def test_english_questions_select_relevant_rag_topics(self):
        self.assertEqual("watering", self.agent._detect_intent("How should I irrigate?"))
        self.assertEqual(
            "fertilizer", self.agent._detect_intent("Should I apply more nitrogen fertilizer?")
        )
        self.assertEqual("spread", self.agent._detect_intent("How does it spread?"))

    def test_context_is_extracted_and_conversation_advances(self):
        started = self.agent.start_diagnosis("Rice__LeafBlast", confidence=0.75)
        reply = self.agent.chat(
            started["session_id"],
            "Lúa gieo được 35 ngày, đang đẻ nhánh. Gần đây mưa nhiều và tôi vừa bón urê.",
        )
        self.assertEqual(35, reply["context"]["age_days"])
        self.assertEqual("đẻ nhánh", reply["context"]["growth_stage"])
        self.assertIn("recent_weather", reply["context"])
        self.assertIn("nitrogen_use", reply["context"])
        self.assertEqual("water_condition", reply["pending_field"])

    def test_age_can_supply_a_clearly_marked_stage_estimate(self):
        started = self.agent.start_diagnosis("Rice__BrownSpot", confidence=0.75)
        reply = self.agent.chat(started["session_id"], "Lúa gieo được 62 ngày")
        self.assertEqual("làm đòng", reply["context"]["growth_stage"])
        self.assertEqual(
            "estimated_from_age", reply["context"]["growth_stage_source"]
        )
        self.assertIn("growth stage is estimated", reply["message"])

    def test_neck_blast_stage_contradiction_is_flagged(self):
        started = self.agent.start_diagnosis("Rice__NeckBlast", confidence=0.84)
        reply = self.agent.chat(
            started["session_id"], "Lúa 35 ngày tuổi và đang đẻ nhánh"
        )
        self.assertIn("not consistent", reply["message"])
        self.assertIn("recheck the image", reply["message"])

    def test_close_top_predictions_are_marked_uncertain(self):
        result = self.agent.start_diagnosis(
            "Rice__BrownSpot",
            confidence=0.61,
            top_predictions=[
                {"class_id": "Rice__BrownSpot", "confidence_score": 0.61},
                {"class_id": "Rice__NarrowBrownLeafSpot", "confidence_score": 0.56},
            ],
        )
        self.assertEqual("uncertain", result["assessment"])
        self.assertIn("uncertain", result["message"])
        self.assertIn("narrow brown leaf spot", result["message"].lower())

    def test_water_answer_uses_context_without_inventing_liters(self):
        started = self.agent.start_diagnosis("Rice__BacterialLeafBlight", 0.88)
        self.agent.chat(started["session_id"], "Cây lúa được 45 ngày")
        reply = self.agent.chat(
            started["session_id"],
            "Ruộng mẫu đang bị ngập và mấy ngày nay mưa nhiều, tưới thế nào?",
        )
        self.assertIn("drainage", reply["message"])
        self.assertNotIn("liters per day", reply["message"])

    def test_pesticide_question_returns_safety_guard_and_source(self):
        started = self.agent.start_diagnosis("Rice__Hispa", 0.9)
        reply = self.agent.chat(
            started["session_id"], "Dùng thuốc gì và pha liều bao nhiêu?"
        )
        self.assertIn("do not choose or mix a pesticide", reply["message"].lower())
        self.assertIn("sansangxuatkhau.ppd.gov.vn", reply["message"])

    def test_follow_up_does_not_repeat_the_initial_diagnosis_intro(self):
        self.agent.llm = RepeatingDiagnosisLLM()
        started = self.agent.start_diagnosis(
            "Rice__LeafBlast",
            confidence=0.82,
            initial_context={
                "age_days": 35,
                "growth_stage": "tillering",
                "recent_weather": "normal",
                "water_condition": "adequate",
                "nitrogen_use": "balanced",
            },
        )
        self.assertIn("The model classified", started["message"])

        reply = self.agent.chat(started["session_id"], "How can I prevent it?")

        self.assertNotIn("The model classified", reply["message"])
        self.assertNotIn("Rice blast", reply["message"])
        self.assertIn("Remove infected plant material", reply["message"])
        self.assertIn(
            "do not repeat the disease label",
            self.agent.llm.calls[-1]["system_prompt"],
        )

    def test_agent_does_not_ask_for_more_context_when_profile_is_complete(self):
        self.agent.llm = UnrequestedQuestionLLM()

        result = self.agent.start_diagnosis(
            "Rice__LeafBlast",
            confidence=0.82,
            initial_context={
                "age_days": 35,
                "growth_stage": "tillering",
                "recent_weather": "normal",
                "water_condition": "adequate",
                "nitrogen_use": "balanced",
                "previous_action": "No treatment yet",
            },
        )

        self.assertIsNone(result["pending_field"])
        self.assertNotIn("?", result["message"])
        self.assertIn("Maintain good airflow", result["message"])


if __name__ == "__main__":
    unittest.main()
